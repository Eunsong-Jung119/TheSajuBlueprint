function parentFactLine(a){
  const d = a.dist || {};
  const distStr = ['비겁','식상','재성','관성','인성'].map(k=>`${k}${d[k]||0}`).join('/');
  return `[${a.who}] ${a.dayPillar} 일주
 · 일간: ${a.dayStem}(${a.dayEl}) — 물상 "${a.mulsang}"  ※물상은 은유일 뿐, 취향으로 쓰지 말 것
 · 일지: ${a.dayBranch}(${a.branchEl}) → 본인 기준 일지십성 = <b>${a.branchSipseong10}</b> (집에서 만드는 정서 공기)
 · 발달십성(원국 가중 1위) = <b>${a.sipseongTop}</b>   [분포 ${distStr}]
 · 부십성(2위) = <b>${a.sipseongSub}</b>
 · 신강약 = <b>${a.level}</b> (지지율 ${a.strengthPct}%)  → 이 방식이 과해지거나 지치는 형태의 근거
 · 용신 ${a.yong} · 희신 ${a.hee}`;
}

function buildParentMessages(parentAn){
  const list = (parentAn||[]).filter(Boolean);
  const same = [];
  if (list.length === 2) {
    if (list[0].sipseongTop === list[1].sipseongTop) same.push('발달십성');
    if (list[0].branchSipseong10 === list[1].branchSipseong10) same.push('일지십성');
    if (list[0].sipseongSub === list[1].sipseongSub) same.push('부십성');
  }
  const diff = [];
  if (list.length === 2) {
    if (list[0].dayEl !== list[1].dayEl) diff.push(`일간 오행(${list[0].dayEl} vs ${list[1].dayEl})`);
    if (list[0].sipseongSub !== list[1].sipseongSub) diff.push(`부십성(${list[0].sipseongSub} vs ${list[1].sipseongSub})`);
    if (list[0].level !== list[1].level) diff.push(`신강약(${list[0].level} vs ${list[1].level})`);
    if (list[0].branchSipseong10 !== list[1].branchSipseong10) diff.push(`일지십성(${list[0].branchSipseong10} vs ${list[1].branchSipseong10})`);
    if (list[0].yong !== list[1].yong) diff.push(`용신(${list[0].yong} vs ${list[1].yong})`);
  }
  const warn = same.length
    ? `\n⚠️⚠️ 두 분은 <b>${same.join('·')}</b>이(가) 같습니다. 그래도 카드가 겹치면 안 됩니다.\n   → 갈라야 할 축: ${diff.length?diff.join(' / '):'일간 물상과 원국 분포의 미세한 차이'}\n   → 이 축들을 근거로 head·lang·body·over·mission을 <b>전부</b> 다르게 쓰세요.`
    : `\n두 분은 축이 충분히 다릅니다. 각자의 결을 자연스럽게 살려 쓰세요.`;
  const facts = list.map(parentFactLine).join('\n\n') + warn;
  return [
    { role:'system', content: PARENT_SYSTEM },
    { role:'user',   content: PARENT_EX_FACTS + '\n\n' + PARENT_SCHEMA },
    { role:'assistant', content: JSON.stringify(PARENT_EX_JSON, null, 1) },
    { role:'user',   content: facts + '\n\n' + PARENT_SCHEMA },
  ];
}
